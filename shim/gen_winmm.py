#!/usr/bin/env python3
"""Generates winmm.def and src/winmm_forward.inc from winmm_exports.txt (public winmm export names).

Every export is a one-instruction thunk `jmp *g_winmm_real[i]`; winmm_forward_init() fills the table
from the system winmm.dll. Run: python3 -I gen_winmm.py
"""
import os

here = os.path.dirname(os.path.abspath(__file__))
names = [n.strip() for n in open(os.path.join(here, "winmm_exports.txt")) if n.strip()]

with open(os.path.join(here, "winmm.def"), "w") as f:
    f.write("LIBRARY winmm.dll\nEXPORTS\n")
    for n in names:
        f.write("    %s = fwd_%s\n" % (n, n))

with open(os.path.join(here, "src", "winmm_forward.inc"), "w") as f:
    f.write("/* generated by shim/gen_winmm.py - do not edit */\n")
    f.write("#define WINMM_FWD_COUNT %d\n" % len(names))
    f.write("void *g_winmm_real[WINMM_FWD_COUNT];\n")
    f.write("static const char *const g_winmm_names[WINMM_FWD_COUNT] = {\n")
    for n in names:
        f.write('    "%s",\n' % n)
    f.write("};\n")
    f.write("__asm__(\n    \".text\\n\"\n")
    for i, n in enumerate(names):
        f.write('    ".globl fwd_%s\\n" "fwd_%s:\\n" "jmp *g_winmm_real+%d(%%rip)\\n"\n' % (n, n, i * 8))
    f.write(");\n")
