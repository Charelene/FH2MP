"""PostgreSQL storage for the LSP stand-in (scores, XP, Drivatars, notifications, players, user content).

PostgreSQL is the durable system of record; the game catalog (cars, tracks, strings, schemas) lives in the same database as the schema
`game` (tools/load_gamedata_pg.py), so state and game data join in one statement. Sessions, tickets and lobbies (xbl.py) and every live
game world (fh2mp_server.py) stay in process memory on purpose: they are leases that should vanish on restart.

Connection: libpq conninfo in FH2MP_PG_DSN (default `dbname=fh2mp`, i.e. the local socket with peer authentication for the service
user), psycopg 3. One connection per thread (ThreadingHTTPServer starts a thread per request), autocommit; client-side binding, so a
NULL parameter never needs a cast. Writes go through `tx()`, which also takes a transaction-scoped advisory lock: write transactions run
one after the other, exactly as the SQLite version's BEGIN IMMEDIATE did, so a read-modify-write cannot interleave with another writer.

The statements in the stores are written with `?` placeholders and a few SQLite-style spellings; `_translate` turns them into
PostgreSQL (`?` -> `%s`, INSERT OR IGNORE -> ON CONFLICT DO NOTHING). `cursor.lastrowid` works for tables with an identity `id`
(RETURNING id is added). Rows are tuples that also answer `row["name"]` (case-insensitively) and `dict(row)`.
Schema changes are numbered entries in MIGRATIONS, applied in order and recorded in `schema_version`.
"""
