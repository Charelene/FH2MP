ADVISORY_LOCK = 7240001          # serialises write transactions (see tx)


class Row(tuple):
    """A result row: a tuple that also answers row["column"] (case-insensitive) and dict(row)."""

    def __getitem__(self, key):
        if isinstance(key, str):
            try:
                return tuple.__getitem__(self, self._idx[key.lower()])
            except KeyError:
                raise KeyError(key) from None
        return tuple.__getitem__(self, key)

    def keys(self):
        return list(self._names)

    def get(self, key, default=None):
        try:
            return self[key]
        except KeyError:
            return default


def _row_factory(cursor):
    names = [c.name for c in cursor.description] if cursor.description else []
    idx = {n.lower(): i for i, n in enumerate(names)}

    def make(values):
        r = Row(values)
        r._names, r._idx = names, idx
        return r
    return make


class _Cursor:
    """What execute() returns: fetch*, iteration, rowcount and (for INSERTs into identity tables) lastrowid."""

    def __init__(self, cur, lastrowid=None):
        self._cur, self.lastrowid = cur, lastrowid
        self.rowcount = cur.rowcount

    def fetchone(self):
        return self._cur.fetchone()

    def fetchall(self):
        return self._cur.fetchall()

    def __iter__(self):
        return iter(self._cur)


_INSERT = re.compile(r"^\s*INSERT\s+(OR\s+IGNORE\s+)?INTO\s+(\w+)", re.I)
_cache = {}


def _translate(sql, with_args):
    """SQLite-style statement -> PostgreSQL: `?` -> `%s` and `%` -> `%%` outside quotes, INSERT OR IGNORE -> ON CONFLICT DO NOTHING."""
    key = (sql, with_args)
    hit = _cache.get(key)
    if hit is not None:
        return hit
    if re.search(r"\bINSERT\s+OR\s+REPLACE\b|\bCOLLATE\s+NOCASE\b|\browid\b", sql, re.I):
        raise ValueError(f"SQLite-only construct in: {sql[:80]}")
    out, i, n, quote = [], 0, len(sql), None
    while i < n:
        ch = sql[i]
        if quote:
            out.append("%%" if ch == "%" and with_args else ch)
            if ch == quote:
                quote = None
        elif ch in "'\"":
            quote = ch
            out.append(ch)
        elif ch == "?" and with_args:
            out.append("%s")
        elif ch == "%" and with_args:
            out.append("%%")
        else:
            out.append(ch)
        i += 1
    text = "".join(out)
    m = _INSERT.match(text)
    if m and m.group(1):
        text = re.sub(r"^(\s*INSERT)\s+OR\s+IGNORE\s+(INTO)", r"\1 \2", text, flags=re.I).rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    if len(_cache) < 2000:
        _cache[key] = text
    return text


def _float_numeric(conn):
    """NUMERIC results (SUM / AVG of integers) come back as float, as SQLite returned them."""
    from psycopg.adapt import Loader

    class FloatLoader(Loader):
        def load(self, data):
            return float(bytes(data).decode())
    conn.adapters.register_loader("numeric", FloatLoader)


class Database:
    def __init__(self, dsn=None):
        self.dsn = dsn or os.environ.get("FH2MP_PG_DSN") or "dbname=fh2mp"
        self.path = re.sub(r"password=\S+", "password=***", self.dsn)       # for log lines
        self._local = threading.local()
        self._all = []                      # every thread's connection, so close() can close them all
        self._migrate()
        self.serial_tables = {r[0] for r in self.query(
            "SELECT table_name FROM information_schema.columns WHERE table_schema='public' AND column_name='id' "
            "AND (is_identity='YES' OR column_default LIKE 'nextval%')")}

    # ---- connections (one per thread)
    def _connect(self):
        conn = psycopg.connect(self.dsn, autocommit=True, row_factory=_row_factory, cursor_factory=psycopg.ClientCursor)
        _float_numeric(conn)
        conn.execute("SET search_path TO public, game")
        conn.execute("SET TIME ZONE 'UTC'")
        return conn

    @property
    def conn(self):
        c = getattr(self._local, "conn", None)
        if c is None or c.closed:
            c = self._local.conn = self._connect()
            self._all = [x for x in self._all if not x.closed] + [c]
        return c

    def _exec(self, conn, sql, args=()):
        text = _translate(sql, bool(args))
        m = _INSERT.match(text)
        want_id = bool(m and m.group(2).lower() in getattr(self, "serial_tables", ()) and "RETURNING" not in text.upper())
        if want_id:
            text += " RETURNING id"
        cur = conn.execute(text, tuple(args) if args else None)
        rid = None
        if want_id and cur.description:
            r = cur.fetchone()
            rid = r[0] if r else None
        return _Cursor(cur, rid)

    def _run(self, sql, args, fetch):
        for attempt in (0, 1):
            try:
                cur = self._exec(self.conn, sql, args)
                return cur.fetchall() if fetch == "all" else cur.fetchone()
            except psycopg.OperationalError:
                if attempt or not self.conn.closed:
                    raise
                self._local.conn = None            # the server went away between requests: reconnect once

    @contextmanager
    def tx(self):
        """A write transaction (COMMIT, or ROLLBACK if the body raises). Takes the advisory lock first, so writers never interleave.
        Yields an object with execute(sql, args) like the old SQLite connection."""
        conn = self.conn
        with conn.transaction():
            conn.execute("SELECT pg_advisory_xact_lock(%s)", (ADVISORY_LOCK,))
            yield _Tx(self, conn)

    def query(self, sql, args=()):
        return self._run(sql, args, "all")

    def one(self, sql, args=()):
        return self._run(sql, args, "one")

    def execute(self, sql, args=()):
        """One statement outside a transaction (reads, mostly); returns a cursor with fetchone / fetchall / iteration."""
        return self._exec(self.conn, sql, args)

    def close(self):
        for c in self._all:
            if not c.closed:
                c.close()
        self._all = []

    # ---- schema
    def _migrate(self):
        conn = self.conn
        with conn.transaction():
            conn.execute("SELECT pg_advisory_xact_lock(%s)", (ADVISORY_LOCK + 1,))
            conn.execute("CREATE TABLE IF NOT EXISTS schema_version (version BIGINT NOT NULL)")
            row = conn.execute("SELECT version FROM schema_version").fetchone()
            version = row[0] if row else 0
            if version > len(MIGRATIONS):
                raise RuntimeError(f"{self.path} is schema v{version}, this build only knows v{len(MIGRATIONS)}")
            for v in range(version, len(MIGRATIONS)):
                for stmt in _statements(MIGRATIONS[v]):
                    conn.execute(stmt)
                _after_migration(conn, v + 1)
            if version == 0:
                conn.execute("INSERT INTO schema_version (version) VALUES (%s)", (len(MIGRATIONS),))
            elif version < len(MIGRATIONS):
                conn.execute("UPDATE schema_version SET version=%s", (len(MIGRATIONS),))

    # ---- meta
    def meta_get(self, key, default=None):
        r = self.one("SELECT value FROM meta WHERE key=?", (key,))
        return r["value"] if r else default


class _Tx:
    def __init__(self, db, conn):
        self._db, self._conn = db, conn

    def execute(self, sql, args=()):
        return self._db._exec(self._conn, sql, args)


def _after_migration(conn, version):
    if version == 1:
        # notification ids must keep growing past anything a client has ever seen: start the sequence at the current time
        conn.execute("SELECT setval(pg_get_serial_sequence('notifications', 'id'), %s)", (int(time.time()) - 1,))


def set_sequence(c, table, value, column="id"):
    """The next id handed out for `table` is value + 1. `c` is a tx() object."""
    value = int(value)
    c.execute("SELECT setval(pg_get_serial_sequence('%s', '%s'), %s, %s)" % (table, column, max(value, 1), "true" if value >= 1 else "false"))


def touch_player(c, xuid, tag="", seen=None, level=None):
    """Creates the player row or refreshes last_seen (and the gamertag / career level when given).
    `c` is a tx() connection."""
    seen = time.time() if seen is None else seen
    c.execute("INSERT INTO players (xuid, gamertag, career_level, first_seen, last_seen) VALUES (?,?,?,?,?) "
              "ON CONFLICT(xuid) DO UPDATE SET last_seen=excluded.last_seen, "
              "gamertag=CASE WHEN excluded.gamertag<>'' THEN excluded.gamertag ELSE players.gamertag END, "
              "career_level=CASE WHEN ? IS NULL THEN players.career_level ELSE excluded.career_level END",
              (xuid, tag or "", level or 0, seen, seen, level))


def _statements(script):
    """Split a migration script into statements: drop `--` comments (they may contain ';'), then split on ';'
    (no function bodies or string literals with '--' or ';' in ours, so a plain split is enough)."""
    text = "\n".join(re.sub(r"--.*$", "", ln) for ln in script.splitlines())
    return [part.strip() for part in text.split(";") if part.strip()]


def open_db(dsn=None):
    """Connects (creating the schema if needed). `dsn`: libpq conninfo, else FH2MP_PG_DSN, else `dbname=fh2mp`."""
    return Database(dsn)
