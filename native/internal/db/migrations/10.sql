
    CREATE TABLE stats_samples (
        at      DOUBLE PRECISION PRIMARY KEY,
        online  BIGINT NOT NULL,
        lobbies BIGINT NOT NULL
    );
    CREATE TABLE mode_results (
        id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        at     DOUBLE PRECISION NOT NULL,
        mode   TEXT NOT NULL,                -- race | team | king | infection
        detail TEXT NOT NULL                 -- JSON: players (xuid, car, rental, team, finish position), winner, hits, ...
    );
    CREATE INDEX mode_results_at ON mode_results (mode, at)
    