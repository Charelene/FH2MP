
    CREATE TABLE players (
        xuid          BIGINT PRIMARY KEY,
        gamertag      TEXT    NOT NULL DEFAULT '',
        career_level  BIGINT  NOT NULL DEFAULT 0,
        first_seen    DOUBLE PRECISION NOT NULL,
        last_seen     DOUBLE PRECISION NOT NULL
    );

    -- One row per accepted score. Raw protocol ids are kept as sent; which direction is "better" is decided
    -- at query time (scoreboard.ASCENDING is still a guess), so nothing here bakes it in.
    CREATE TABLE score_submissions (
        id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        xuid       BIGINT NOT NULL,
        sb         BIGINT NOT NULL,      -- scoreboardType
        st         BIGINT NOT NULL,      -- scoreType
        gsid       BIGINT NOT NULL,      -- gameScoreboardId
        track      BIGINT NOT NULL,
        car        BIGINT NOT NULL,
        cls        BIGINT NOT NULL,
        cpi        DOUBLE PRECISION NOT NULL,
        score      DOUBLE PRECISION NOT NULL,      -- decoded IEEE double (finite only, see ScoreStore.submit)
        clean      BIGINT NOT NULL,
        stm        BIGINT NOT NULL,
        tcs        BIGINT NOT NULL,
        abs        BIGINT NOT NULL,
        submitted  DOUBLE PRECISION NOT NULL,
        score_id   BYTEA                 -- the random scoreId SubmitScore hands out; the ghost upload refers to it
    );
    CREATE INDEX score_board ON score_submissions (sb, st, track, xuid);
    CREATE INDEX score_player ON score_submissions (xuid, sb, st, track);
    CREATE INDEX score_by_scoreid ON score_submissions (score_id);

    -- Ghosts: the client uploads a replay blob for a score (Scoreboard.UploadFile); DownloadFile serves it to whoever races it.
    CREATE TABLE score_ghosts (
        submission_id BIGINT PRIMARY KEY REFERENCES score_submissions (id) ON DELETE CASCADE,
        data          BYTEA NOT NULL,
        uploaded      DOUBLE PRECISION NOT NULL
    );

    CREATE TABLE player_xp (
        xuid     BIGINT PRIMARY KEY,
        xp       DOUBLE PRECISION NOT NULL,
        updated  DOUBLE PRECISION NOT NULL
    );

    -- A player's own Drivatar. The wire-shaped record (UserInfo, Curves, Segments, ...) stays opaque JSON text;
    -- the columns are the fields we select on. seq keeps insertion order.
    CREATE TABLE drivatars (
        seq        BIGINT GENERATED ALWAYS AS IDENTITY,
        xuid       BIGINT PRIMARY KEY,
        gamertag   TEXT    NOT NULL DEFAULT '',
        skill      BIGINT  NOT NULL,
        wristband  BIGINT  NOT NULL,
        locked     BIGINT  NOT NULL DEFAULT 0,
        record     TEXT    NOT NULL,
        updated    DOUBLE PRECISION NOT NULL
    );
    CREATE INDEX drivatar_skill ON drivatars (skill, wristband);

    -- Immutable content; per-player state lives in notification_receipts so one player reading, clearing or
    -- claiming a broadcast does not change it for everyone. xuid 0 = broadcast. The identity column never reuses an id:
    -- the client keys its Message Center on them (the sequence starts at the current time, see _after_migration).
    CREATE TABLE notifications (
        id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        type     BIGINT NOT NULL,
        message  TEXT   NOT NULL DEFAULT '',
        sra      TEXT   NOT NULL DEFAULT '',
        sent     BIGINT NOT NULL,        -- Windows FILETIME, as the client wants it
        xuid     BIGINT NOT NULL DEFAULT 0,
        car_id   BIGINT,
        params   TEXT   NOT NULL DEFAULT '{}'
    );
    CREATE INDEX notification_xuid ON notifications (xuid);

    CREATE TABLE notification_receipts (
        notification_id BIGINT NOT NULL REFERENCES notifications (id) ON DELETE CASCADE,
        xuid            BIGINT NOT NULL,
        read_at         DOUBLE PRECISION,
        cleared_at      DOUBLE PRECISION,
        claimed_at      DOUBLE PRECISION,
        PRIMARY KEY (notification_id, xuid)
    );

    CREATE TABLE meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);

    -- Monthly Rivals events. A rotation is generated once (server/rivals.py), stored here and never regenerated, so an event id
    -- keeps its meaning (track, laps, restriction, text) after restarts and code changes; scores, ghosts and rival notifications
    -- reference these ids. Ended rotations stay for history.
    CREATE TABLE rival_events (
        id          BIGINT PRIMARY KEY,           -- 16-bit on the wire (ForzaTimeTrial.id)
        month       BIGINT NOT NULL,              -- months since 2026-01
        reroll      BIGINT NOT NULL,
        idx         BIGINT NOT NULL,
        track       BIGINT NOT NULL,
        laps        BIGINT NOT NULL,
        length      DOUBLE PRECISION NOT NULL,    -- metres, from the route file
        kind        TEXT   NOT NULL,
        attrs       TEXT   NOT NULL,              -- JSON: CarRestrictions attributes
        cls         BIGINT,                       -- class used for the rival time model
        name        TEXT   NOT NULL,
        trackname   TEXT   NOT NULL,
        description TEXT   NOT NULL,
        created     DOUBLE PRECISION NOT NULL,
        tod         BIGINT,                       -- GameOptions TimeOfDay in seconds since midnight (NULL = the world's time)
        weather     BIGINT,                       -- AtmosphericPresetIndex (WeatherPreset.Id)
        wetness     DOUBLE PRECISION,
        precip      DOUBLE PRECISION
    );
    CREATE INDEX rival_events_rotation ON rival_events (month, reroll, idx);

    -- User-generated content (server/ugc.py): chunked blobs, versioned items (livery / layer group / tune) and the public storefront
    -- listing with counters. Large values are stored LZMA-packed by ugc.pack.
    CREATE TABLE ugc_blobs (
        id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- the client's contentFileId
        owner          BIGINT NOT NULL,
        user_file_name TEXT   NOT NULL DEFAULT '',
        total_size     BIGINT NOT NULL,
        received       BIGINT NOT NULL DEFAULT 0,
        data           BYTEA  NOT NULL,
        created        DOUBLE PRECISION NOT NULL
    );
    CREATE INDEX ugc_blobs_name ON ugc_blobs (owner, user_file_name);

    CREATE TABLE ugc_versioned (
        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,      -- versionedLiveryId / versionedTuneId / versionedLayerGroupId
        kind        TEXT   NOT NULL,                       -- livery | tune | layergroup
        car_id      BIGINT,
        name        TEXT   NOT NULL DEFAULT '',
        creator     BIGINT NOT NULL,
        layers      BIGINT NOT NULL DEFAULT 0,
        data        BYTEA,
        thumb       BYTEA,
        thumb_small BYTEA,
        parts       TEXT,                                   -- tune: installed parts (JSON)
        tuning      TEXT,                                   -- tune: tuning values (JSON)
        refs        BIGINT NOT NULL DEFAULT 1,
        created     DOUBLE PRECISION NOT NULL
    );

    CREATE TABLE ugc_files (
        id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,     -- the storefront file id
        kind         TEXT   NOT NULL,                      -- livery | tune | layergroup | photo | replay
        type         BIGINT NOT NULL DEFAULT 0,            -- the client's file type number
        owner        BIGINT NOT NULL,
        title        TEXT   NOT NULL DEFAULT '',
        description  TEXT   NOT NULL DEFAULT '',
        created      DOUBLE PRECISION NOT NULL,
        payload_size BIGINT NOT NULL DEFAULT 0,
        preview      BYTEA,
        versioned_id BIGINT,
        blob_id      BIGINT,
        car_id       BIGINT,
        make_id      BIGINT,
        model_id     BIGINT,
        class_id     BIGINT,
        keyword1     BIGINT NOT NULL DEFAULT 0,
        keyword2     BIGINT NOT NULL DEFAULT 0,
        env          BIGINT,
        track        BIGINT,
        pi           BIGINT,
        downloads    BIGINT NOT NULL DEFAULT 0,
        likes        BIGINT NOT NULL DEFAULT 0,
        uses         BIGINT NOT NULL DEFAULT 0,
        views        BIGINT NOT NULL DEFAULT 0,
        popularity   BIGINT NOT NULL DEFAULT 0,
        removed      BIGINT NOT NULL DEFAULT 0
    );
    CREATE INDEX ugc_files_kind ON ugc_files (kind, removed, likes);
    CREATE INDEX ugc_files_owner ON ugc_files (owner, type, removed);
    