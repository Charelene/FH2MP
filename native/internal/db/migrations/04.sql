
    CREATE TABLE shared_textures (
        id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        owner     BIGINT NOT NULL,
        livery    BYTEA  NOT NULL,                 -- the client's blobs, kept as sent (LZMA-packed, ugc.pack)
        thumbnail BYTEA  NOT NULL,
        created   DOUBLE PRECISION NOT NULL
    );

    CREATE TABLE shared_cars (
        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        club_id     BIGINT NOT NULL REFERENCES clubs (id) ON DELETE CASCADE,
        owner       BIGINT NOT NULL,
        game_car_id BYTEA  NOT NULL,               -- the owner's garage car (guid): sharing it again overwrites this row
        profile_id  BYTEA  NOT NULL,
        model_id    BIGINT NOT NULL,               -- the car id (Data_Car.Id = ModelId for every car)
        car         TEXT   NOT NULL,               -- the rest of completeCarData as JSON (colours, ratings, ...)
        textures_id BIGINT NOT NULL DEFAULT 0,
        livery      BYTEA  NOT NULL,
        tuning      BYTEA  NOT NULL,
        version     BIGINT NOT NULL DEFAULT 1,
        shared      DOUBLE PRECISION NOT NULL,
        last_used   DOUBLE PRECISION NOT NULL,
        race_count  BIGINT NOT NULL DEFAULT 0
    );
    CREATE INDEX shared_cars_club ON shared_cars (club_id, shared);
    CREATE UNIQUE INDEX shared_cars_owner_car ON shared_cars (owner, game_car_id);
    