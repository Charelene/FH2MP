
    CREATE TABLE clubs (
        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        tag         TEXT   NOT NULL,                  -- 3 or 4 characters, unique ignoring case
        name        TEXT   NOT NULL,
        description TEXT   NOT NULL DEFAULT '',
        privacy     BIGINT NOT NULL DEFAULT 1,        -- 1 open (confirmed), 2 invite only, 3 private [guess]; 0 means "any" in searches
        region      BIGINT NOT NULL DEFAULT 0,        -- keyword ids (clubs.KEYWORDS), 0 = none
        attitude    BIGINT NOT NULL DEFAULT 0,
        interest    BIGINT NOT NULL DEFAULT 0,
        created     DOUBLE PRECISION NOT NULL
    );
    CREATE UNIQUE INDEX clubs_tag ON clubs (lower(tag));

    -- A player is in at most one club (xuid is the key); role 0 member, 1 co-leader, 2 leader [guess]
    CREATE TABLE club_members (
        xuid           BIGINT PRIMARY KEY,
        club_id        BIGINT NOT NULL REFERENCES clubs (id) ON DELETE CASCADE,
        role           BIGINT NOT NULL DEFAULT 0,
        joined         DOUBLE PRECISION NOT NULL,
        status_changed DOUBLE PRECISION NOT NULL
    );
    CREATE INDEX club_members_club ON club_members (club_id, role);

    CREATE TABLE club_invites (
        id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        club_id BIGINT NOT NULL REFERENCES clubs (id) ON DELETE CASCADE,
        sponsor BIGINT NOT NULL,
        invitee BIGINT NOT NULL,
        created DOUBLE PRECISION NOT NULL
    );
    CREATE INDEX club_invites_invitee ON club_invites (invitee);

    CREATE TABLE club_requests (
        club_id BIGINT NOT NULL REFERENCES clubs (id) ON DELETE CASCADE,
        xuid    BIGINT NOT NULL,
        created DOUBLE PRECISION NOT NULL,
        PRIMARY KEY (club_id, xuid)
    );

    CREATE TABLE club_removal_votes (
        club_id BIGINT NOT NULL REFERENCES clubs (id) ON DELETE CASCADE,
        target  BIGINT NOT NULL,
        voter   BIGINT NOT NULL,
        created DOUBLE PRECISION NOT NULL,
        PRIMARY KEY (club_id, target, voter)
    );

    -- Noticeboard posts; each member gets a Message Center notification (notification_ids, JSON) that is removed with the post
    CREATE TABLE club_notices (
        id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        club_id          BIGINT NOT NULL REFERENCES clubs (id) ON DELETE CASCADE,
        sender           BIGINT NOT NULL,
        role             BIGINT NOT NULL,
        message          TEXT   NOT NULL,
        created          DOUBLE PRECISION NOT NULL,
        notification_ids TEXT   NOT NULL DEFAULT '[]'
    );

    CREATE TABLE club_history (
        id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        xuid      BIGINT NOT NULL,
        club_id   BIGINT NOT NULL,
        club_name TEXT   NOT NULL,
        action    BIGINT NOT NULL,
        role      BIGINT NOT NULL DEFAULT 0,
        created   DOUBLE PRECISION NOT NULL
    );
    CREATE INDEX club_history_xuid ON club_history (xuid, id);

    CREATE TABLE club_prefs (xuid BIGINT PRIMARY KEY, accepts BIGINT NOT NULL DEFAULT 1);
    