
    CREATE TABLE friend_requests (
        sender BIGINT NOT NULL REFERENCES accounts(xuid),
        recipient BIGINT NOT NULL REFERENCES accounts(xuid),
        created DOUBLE PRECISION NOT NULL,
        PRIMARY KEY (sender, recipient), CHECK (sender <> recipient)
    );
    CREATE INDEX friend_requests_recipient ON friend_requests(recipient);
    CREATE TABLE launcher_messages (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        sender BIGINT NOT NULL REFERENCES accounts(xuid),
        channel TEXT NOT NULL,
        body TEXT NOT NULL CHECK (length(body) BETWEEN 1 AND 2000),
        created DOUBLE PRECISION NOT NULL
    );
    CREATE INDEX launcher_messages_channel ON launcher_messages(channel, id);
    CREATE TABLE launcher_chat_reads (
        xuid BIGINT NOT NULL REFERENCES accounts(xuid),
        channel TEXT NOT NULL,
        last_id BIGINT NOT NULL DEFAULT 0,
        PRIMARY KEY (xuid, channel)
    );
    